-- DungeonQuestData
-- Static data for dungeon quest tables.
-- Exposes DungeonQuestData, an array of dungeon tables (name, columns, rows)
-- in display order, consumed by DungeonQuests.lua via DataTable. Zone id/boss
-- levels/mob level range live separately in DungeonInfoData.lua.

-- Column layout for a dungeon's quest table (see DataTable.lua). Widths sum
-- to comfortably fit the 770px main window (see mainframe.lua) alongside
-- the vertical scrollbar - unlike Mining/Herbalism's DataTable, every
-- column is always shown (no per-expansion filtering), so the sum has to
-- fit on its own without that headroom.
-- Shared with the Effort column's info legend below, so the legend's swatch
-- colors can never drift out of sync with the cell backgrounds they describe.
local EffortColors = {
    Low    = { 0.20, 0.80, 0.20 },
    Medium = { 0.85, 0.80, 0.10 },
    High   = { 0.90, 0.15, 0.15 },
}

